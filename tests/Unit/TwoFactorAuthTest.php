<?php
declare(strict_types=1);

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\TestCase;

require_once __DIR__ . '/../../modules/two_factor.php';

/**
 * Unit tests for TwoFactorAuth — RFC 6238 TOTP core logic.
 *
 * Security-critical code: target coverage 100%.
 */
#[CoversClass(TwoFactorAuth::class)]
final class TwoFactorAuthTest extends TestCase
{
    // ---------------------------------------------------------------
    // generateSecret()
    // ---------------------------------------------------------------

    public function testGenerateSecretIsSixteenCharacters(): void
    {
        $secret = TwoFactorAuth::generateSecret();
        $this->assertSame(16, strlen($secret));
    }

    public function testGenerateSecretUsesOnlyBase32Alphabet(): void
    {
        // RFC 4648 Base32 (no padding used by TOTP secrets)
        $this->assertMatchesRegularExpression('/^[A-Z2-7]+$/', TwoFactorAuth::generateSecret());
    }

    public function testGenerateSecretIsUniqueAcrossCalls(): void
    {
        $secrets = [];
        for ($i = 0; $i < 50; $i++) {
            $secrets[] = TwoFactorAuth::generateSecret();
        }
        $this->assertCount(50, array_unique($secrets), 'Secrets must be cryptographically random, not repeating');
    }

    // ---------------------------------------------------------------
    // getOtpAuthUri() / getQRCodeUrl()
    // ---------------------------------------------------------------

    public function testOtpAuthUriContainsSecretAndParams(): void
    {
        $uri = TwoFactorAuth::getOtpAuthUri('ABC234DEF567', 'user@example.com');

        $this->assertStringStartsWith('otpauth://totp/', $uri);
        $this->assertStringContainsString('secret=ABC234DEF567', $uri);
        $this->assertStringContainsString('issuer=Adsbooster.net', $uri);
        $this->assertStringContainsString('algorithm=SHA1', $uri);
        $this->assertStringContainsString('digits=6', $uri);
        $this->assertStringContainsString('period=30', $uri);
    }

    public function testOtpAuthUriUrlEncodesSpecialCharactersInEmail(): void
    {
        $uri = TwoFactorAuth::getOtpAuthUri('ABC234DEF567', 'user+tag@example.com');
        $this->assertStringContainsString(rawurlencode('Adsbooster.net:user+tag@example.com'), $uri);
    }

    public function testQRCodeUrlWrapsOtpAuthUriEncoded(): void
    {
        $url = TwoFactorAuth::getQRCodeUrl('ABC234DEF567', 'user@example.com');
        $this->assertStringStartsWith('https://api.qrserver.com/v1/create-qr-code/?size=256x256&margin=10&data=', $url);
        $this->assertStringContainsString(rawurlencode('otpauth://totp/'), $url);
    }

    // ---------------------------------------------------------------
    // verifyCode()
    // ---------------------------------------------------------------

    public function testVerifyCodeRejectsNonNumericInput(): void
    {
        $secret = TwoFactorAuth::generateSecret();
        $this->assertFalse(TwoFactorAuth::verifyCode($secret, 'abcdef'));
        $this->assertFalse(TwoFactorAuth::verifyCode($secret, '12a456'));
        $this->assertFalse(TwoFactorAuth::verifyCode($secret, ''));
        $this->assertFalse(TwoFactorAuth::verifyCode($secret, ' 12345'));
    }

    public function testVerifyCodeRejectsWrongLength(): void
    {
        $secret = TwoFactorAuth::generateSecret();
        $this->assertFalse(TwoFactorAuth::verifyCode($secret, '12345'));
        $this->assertFalse(TwoFactorAuth::verifyCode($secret, '1234567'));
    }

    public function testVerifyCodeRejectsImpossibleCode(): void
    {
        // 999999 colliding with a valid step is astronomically unlikely
        // across ±1 window, but assert false rather than throwing.
        $this->assertIsBool(TwoFactorAuth::verifyCode(TwoFactorAuth::generateSecret(), '999999'));
    }

    public function testVerifyCodeAcceptsCodeGeneratedByIndependentRFC6238Implementation(): void
    {
        // Recompute the expected TOTP with an independent implementation
        // (RFC 4226 HOTP via hash_hmac) and confirm verifyCode() accepts it.
        $secret = TwoFactorAuth::generateSecret();

        $key = $this->base32DecodeRFC4648($secret);
        $timeStep = (int) floor(time() / 30);
        $expected = $this->hotp($key, $timeStep);
        $expectedPrev = $this->hotp($key, $timeStep - 1);
        $expectedNext = $this->hotp($key, $timeStep + 1);

        $this->assertTrue(
            TwoFactorAuth::verifyCode($secret, $expected)
            || TwoFactorAuth::verifyCode($secret, $expectedPrev)
            || TwoFactorAuth::verifyCode($secret, $expectedNext),
            'A code generated by an independent RFC 6238 implementation must verify (step boundary tolerance)'
        );
    }

    public function testVerifyCodeRejectsCodeFromDistantTimeStep(): void
    {
        $secret = TwoFactorAuth::generateSecret();
        $key = $this->base32DecodeRFC4648($secret);
        $farFutureCode = $this->hotp($key, ((int) floor(time() / 30)) + 100);

        $this->assertFalse(TwoFactorAuth::verifyCode($secret, $farFutureCode));
    }

    public function testVerifyCodeIsTimingSafeAgainstMalformedSecrets(): void
    {
        // Invalid Base32 must not throw (base32Decode edge case)
        $this->assertFalse(TwoFactorAuth::verifyCode('!!!', '123456'));
        $this->assertFalse(TwoFactorAuth::verifyCode('', '123456'));
    }

    // ---------------------------------------------------------------
    // generateBackupCodes()
    // ---------------------------------------------------------------

    public function testBackupCodesReturnsTenCodes(): void
    {
        $codes = TwoFactorAuth::generateBackupCodes();
        $this->assertCount(10, $codes);
    }

    public function testBackupCodesFormatIsXXXxxXXXXx(): void
    {
        foreach (TwoFactorAuth::generateBackupCodes() as $entry) {
            $this->assertMatchesRegularExpression('/^[A-Z0-9]{5}-[A-Z0-9]{5}$/', $entry['code']);
            $this->assertFalse($entry['used']);
        }
    }

    public function testBackupCodesAreUnique(): void
    {
        $codes = array_column(TwoFactorAuth::generateBackupCodes(), 'code');
        $this->assertCount(10, array_unique($codes));
    }

    // ---------------------------------------------------------------
    // Independent RFC reference implementation (test oracle)
    // ---------------------------------------------------------------

    private function base32DecodeRFC4648(string $b32): string
    {
        $alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
        $out = '';
        $bits = 0;
        $buffer = 0;
        foreach (str_split(strtoupper($b32)) as $char) {
            $pos = strpos($alphabet, $char);
            if ($pos === false) {
                continue;
            }
            $buffer = ($buffer << 5) | $pos;
            $bits += 5;
            if ($bits >= 8) {
                $out .= chr(($buffer >> ($bits - 8)) & 0xFF);
                $bits -= 8;
            }
        }
        return $out;
    }

    private function hotp(string $key, int $counter): string
    {
        $binCounter = pack('N*', 0) . pack('N*', $counter);
        $hash = hash_hmac('sha1', $binCounter, $key, true);
        $offset = ord(substr($hash, -1)) & 0x0F;
        $value = (
            ((ord($hash[$offset]) & 0x7F) << 24)
            | ((ord($hash[$offset + 1]) & 0xFF) << 16)
            | ((ord($hash[$offset + 2]) & 0xFF) << 8)
            | (ord($hash[$offset + 3]) & 0xFF)
        );
        return str_pad((string) ($value % 1_000_000), 6, '0', STR_PAD_LEFT);
    }
}
