<?php
declare(strict_types=1);

/**
 * Google Gemini Image Engine — Adsbooster.net
 *
 * Generates production-ready ad images and routes them across every
 * configured provider CONCURRENTLY (curl_multi). The first valid image wins,
 * so a dead or slow provider never delays a working one:
 *
 *   • Gemini  (gemini-3-pro-image-preview → gemini-2.5-flash-image → …)
 *             when GEMINI_API_KEY is configured ("Nano Banana 2").
 *   • NVIDIA  NIM image function (flux.1-schnell on ai.api.nvidia.com) when
 *             NVIDIA_API_KEY is configured. A hard failure opens a 30-minute
 *             file circuit breaker (cache/) so a disabled NIM account never
 *             adds latency; the route auto-activates again on success.
 *   • Pollinations (free, keyless) — always in the pool, so generation never
 *             dead-ends while premium keys are missing or quota-exhausted.
 *
 * Generated bytes are stored same-origin under assets/uploads/ai/gemini/
 * (uploads dirs disable script execution) and returned as relative +
 * absolute URLs with honest provenance in the 'model' field.
 *
 * Key resolution: GEMINI_API_KEY / NVIDIA_API_KEY constant → env var →
 * admin site setting — same pipeline as api_key().
 */

require_once __DIR__ . '/../config/site_setting_and_config.php';

class GeminiEngine
{
    private const API_BASE = 'https://generativelanguage.googleapis.com/v1beta';

    /** Image model priority: newest/most capable first. */
    private const IMAGE_MODELS = [
        'gemini-3-pro-image-preview',                     // Nano Banana 2
        'gemini-2.5-flash-image',                         // Nano Banana
        'gemini-2.0-flash-preview-image-generation',      // legacy preview
    ];

    /** Video (Veo) model priority used by AIVideoEngine submissions. */
    public const VIDEO_MODELS = [
        'veo-3.1-generate-preview',
        'veo-3.0-generate-preview',
        'veo-3.0-generate-001',
    ];

    /** Pollinations anonymous free tier exhausted for this PHP request (skip remaining). */
    private static bool $pollinationsExhausted = false;

    /** NVIDIA image route already failed within this PHP request (skip remaining). */
    private static bool $nvidiaBrokenThisRequest = false;

    /** NVIDIA circuit-breaker cache file (relative to ROOT_PATH). */
    private const NVIDIA_BREAKER_FILE = 'cache/nvidia_image_circuit.json';

    public static function key(): string
    {
        if (function_exists('api_key')) {
            return (string)api_key('GEMINI_API_KEY', 'gemini_api_key', '');
        }
        return defined('GEMINI_API_KEY') ? (string)GEMINI_API_KEY : (string)(getenv('GEMINI_API_KEY') ?: '');
    }

    public static function hasKey(): bool
    {
        return self::key() !== '';
    }

    /**
     * Generate an image for $prompt and persist it same-origin.
     *
     * @param int    $width   Target width hint (mapped to a supported aspect ratio)
     * @param int    $height  Target height hint
     * @param ?string $saveAs Optional filename (sanitised); random when null
     * @return array{path:string,url:string,model:string,mime:string}|null
     *         null when every route failed (callers keep curated fallbacks).
     */
    public static function generateImage(string $prompt, int $width = 1024, int $height = 1024, ?string $saveAs = null): ?array
    {
        $prompt = trim($prompt);
        if ($prompt === '') {
            return null;
        }

        $key    = self::key();
        $aspect = self::aspectFor($width, $height);

        // ── Build the concurrent route pool ──────────────────────
        $jobs = [];

        if ($key !== '') {
            // First model revision joins the race; the remaining revisions
            // are the sequential retry if everything in the pool fails.
            $jobs['gemini'] = self::geminiJob(self::IMAGE_MODELS[0], $key, $prompt, $aspect, true);
        }

        if (self::nvidiaAvailable()) {
            $jobs['nvidia'] = self::nvidiaJob($prompt);
        }

        if (!self::$pollinationsExhausted) {
            $jobs['pollinations'] = self::pollinationsJob($prompt, $width, $height);
        }

        if ($jobs !== []) {
            $winner = self::raceJobs($jobs, $prompt, $width, $height, $saveAs);
            if ($winner !== null) {
                return $winner;
            }
        }

        // ── Everything in the pool failed: cheap sequential retries ──
        if ($key !== '') {
            foreach (array_slice(self::IMAGE_MODELS, 1) as $model) {
                $bytes = self::requestImage($model, $key, $prompt, $aspect);
                if ($bytes === null) {
                    continue;
                }
                $saved = self::storeImage($bytes['data'], $bytes['mime'], $saveAs);
                if ($saved === null) {
                    continue;
                }
                return [
                    'path'  => $saved,
                    'url'   => BASE_URL . '/' . $saved,
                    'model' => $model,
                    'mime'  => $bytes['mime'],
                ];
            }
        }

        // Pollinations: wait out an advertised short rate-limit window and
        // retry once before giving up (the pool attempt may have raced a
        // throttled window).
        if (!self::$pollinationsExhausted) {
            $pollinations = self::pollinationsImage($prompt, $width, $height, $saveAs);
            if ($pollinations !== null) {
                return $pollinations;
            }
        }

        return null;
    }

    /**
     * True when the response payload contains at least one image part.
     * Helper for callers that want to pre-flight availability cheaply.
     */
    public static function ready(): bool
    {
        return self::hasKey();
    }

    // ─── concurrent race ─────────────────────────────────────────

    /**
     * Run every prepared route concurrently and return the FIRST valid image.
     * Handles are cancelled as soon as a winner appears, so a dead provider
     * never adds latency to the result.
     *
     * @param array<string,array{ch:CurlHandle,label:string}> $jobs
     */
    private static function raceJobs(array $jobs, string $prompt, int $width, int $height, ?string $saveAs): ?array
    {
        $mh = curl_multi_init();
        foreach ($jobs as $job) {
            curl_multi_add_handle($mh, $job['ch']);
        }

        $done     = [];
        $winner   = null;
        $deadline = microtime(true) + 90;
        $running  = 1;

        do {
            curl_multi_exec($mh, $running);

            while (($info = curl_multi_info_read($mh)) !== false) {
                foreach ($jobs as $id => $job) {
                    if ($info['handle'] !== $job['ch'] || isset($done[$id])) {
                        continue;
                    }
                    $code = (int)curl_getinfo($job['ch'], CURLINFO_HTTP_CODE);
                    $body = (string)curl_multi_getcontent($job['ch']);
                    $done[$id] = ['code' => $code, 'body' => $body, 'at' => microtime(true)];

                    // First valid image wins — stop the pool immediately.
                    if ($code >= 200 && $code < 300) {
                        $bytes = $id === 'gemini'
                            ? self::parseGeminiImageResponse($body)
                            : ($id === 'nvidia'
                                ? self::parseNvidiaImageResponse($body)
                                : self::parseImageBytes($body));
                        if ($bytes !== null) {
                            $winner = self::persistImage($bytes, $id, $saveAs);
                            if ($winner !== null) {
                                break 2;
                            }
                        }
                    }
                }
            }

            if ($winner === null && $running > 0 && count($done) < count($jobs)) {
                curl_multi_select($mh, 1.0);
            }
        } while ($winner === null && $running > 0 && count($done) < count($jobs) && microtime(true) < $deadline);

        foreach ($jobs as $job) {
            curl_multi_remove_handle($mh, $job['ch']);
            curl_close($job['ch']);
        }
        curl_multi_close($mh);

        // Route health bookkeeping (runs whether or not a route won):
        // a failed NVIDIA response opens the circuit; a NVIDIA call that
        // never completed (hung) counts a miss so a permanently dead
        // function stops costing a call per generation.
        if (isset($jobs['nvidia'])) {
            self::$nvidiaBrokenThisRequest = true;
            if (isset($done['nvidia'])) {
                if ($done['nvidia']['code'] < 200 || $done['nvidia']['code'] >= 300) {
                    self::nvidiaTripBreaker();
                    error_log('NVIDIA image route failed in race (HTTP ' . $done['nvidia']['code'] . '); circuit opened for 30 minutes.');
                }
            } elseif ($winner === null || $winner['model'] !== self::nvidiaModelName()) {
                self::nvidiaNoteMiss();
            }
        }

        if ($winner !== null) {
            return $winner;
        }

        if (isset($done['pollinations']) && ($done['pollinations']['code'] === 402 || $done['pollinations']['code'] === 429)) {
            self::$pollinationsExhausted = true;
            error_log('Pollinations free-tier limit reached; skipping for the rest of this request.');
        }

        return null;
    }

    /**
     * Store image bytes same-origin and build the public result payload.
     */
    private static function persistImage(array $bytes, string $route, ?string $saveAs): ?array
    {
        $saved = self::storeImage($bytes['data'], $bytes['mime'], $saveAs);
        if ($saved === null) {
            return null;
        }
        if ($route === 'nvidia') {
            self::nvidiaClearBreaker();
        }
        $model = match ($route) {
            'gemini'      => self::IMAGE_MODELS[0],
            'nvidia'      => self::nvidiaModelName(),
            'pollinations' => 'pollinations-flux',
            default       => $route,
        };
        return [
            'path'  => $saved,
            'url'   => BASE_URL . '/' . $saved,
            'model' => $model,
            'mime'  => $bytes['mime'],
        ];
    }

    // ─── Gemini ──────────────────────────────────────────────────

    private static function requestImage(string $model, string $key, string $prompt, string $aspect): ?array
    {
        // First attempt with aspect guidance; some model revisions reject
        // imageConfig with 400 — retry once without it before moving on.
        foreach ([true, false] as $withImageConfig) {
            $job = self::geminiJob($model, $key, $prompt, $aspect, $withImageConfig);
            $response = curl_exec($job['ch']);
            $code     = (int)curl_getinfo($job['ch'], CURLINFO_HTTP_CODE);
            $err      = curl_error($job['ch']);
            curl_close($job['ch']);

            if ($response === false || $code < 200 || $code >= 300) {
                $snippet = $response === false ? $err : mb_substr((string)$response, 0, 400);
                error_log("GeminiEngine[{$model}] HTTP {$code}: {$snippet}");
                // Rate limit: stop hammering, next model likely shares quota.
                if ($code === 429) {
                    return null;
                }
                // Auth / invalid-key: retrying with a different payload shape
                // will not help — the key itself is rejected. Fail fast.
                if ($code === 401 || $code === 403) {
                    return null;
                }
                if ($code === 400 && str_contains((string)$response, 'API_KEY_INVALID')) {
                    return null;
                }
                // Other 4xx: possibly a model/param problem → next shape or model.
                continue;
            }

            $bytes = self::parseGeminiImageResponse((string)$response);
            if ($bytes !== null) {
                return $bytes;
            }
            // Well-formed 200 without image data (safety block, text-only): try next.
            error_log("GeminiEngine[{$model}] response contained no image part");
            return null;
        }

        return null;
    }

    /**
     * Build a prepared cURL handle for one Gemini generateContent attempt.
     * Shared by the sequential path and the concurrent race.
     */
    private static function geminiJob(string $model, string $key, string $prompt, string $aspect, bool $withImageConfig): array
    {
        $payload = $withImageConfig
            ? json_encode([
                'contents' => [
                    ['parts' => [['text' => $prompt]]],
                ],
                'generationConfig' => [
                    'responseModalities' => ['IMAGE', 'TEXT'],
                    'imageConfig'        => ['aspectRatio' => $aspect],
                ],
            ])
            : json_encode([
                'contents' => [
                    ['parts' => [['text' => $prompt . " (landscape/portrait framing as appropriate, high detail, no text overlays)"]]],
                ],
                'generationConfig' => ['responseModalities' => ['IMAGE', 'TEXT']],
            ]);

        $ch = curl_init(self::API_BASE . '/models/' . $model . ':generateContent?key=' . urlencode($key));
        curl_setopt_array($ch, [
            CURLOPT_POST           => true,
            CURLOPT_POSTFIELDS     => $payload,
            CURLOPT_HTTPHEADER     => ['Content-Type: application/json'],
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT        => 60,
            CURLOPT_SSL_VERIFYPEER => true,
            CURLOPT_SSL_VERIFYHOST => 2,
        ]);
        if (function_exists('ca_curl_setopt')) {
            ca_curl_setopt($ch);
        }
        return ['ch' => $ch, 'label' => 'GeminiEngine[' . $model . ']'];
    }

    /**
     * Extract the first inline image part from a generateContent response.
     *
     * @return array{data:string,mime:string}|null
     */
    private static function parseGeminiImageResponse(string $response): ?array
    {
        $json = json_decode($response, true);
        foreach ((array)($json['candidates'] ?? []) as $candidate) {
            foreach ((array)($candidate['content']['parts'] ?? []) as $part) {
                if (!empty($part['inlineData']['data'])) {
                    $data = base64_decode((string)$part['inlineData']['data'], true);
                    if ($data !== false && $data !== '') {
                        return [
                            'data' => $data,
                            'mime' => (string)($part['inlineData']['mimeType'] ?? 'image/png'),
                        ];
                    }
                }
            }
        }
        return null;
    }

    // ─── NVIDIA NIM image route ──────────────────────────────────

    private static function nvidiaApiKey(): string
    {
        if (function_exists('api_key')) {
            return (string)api_key('NVIDIA_API_KEY', 'nvidia_api_key', '');
        }
        return defined('NVIDIA_API_KEY') ? (string)NVIDIA_API_KEY : (string)(getenv('NVIDIA_API_KEY') ?: '');
    }

    /** NVIDIA image route enabled = key present + circuit breaker closed. */
    private static function nvidiaAvailable(): bool
    {
        return self::nvidiaApiKey() !== ''
            && !self::$nvidiaBrokenThisRequest
            && !self::nvidiaBreakerOpen();
    }

    private static function nvidiaModelName(): string
    {
        $url = defined('NVIDIA_IMAGE_URL') ? NVIDIA_IMAGE_URL : 'https://ai.api.nvidia.com/v1/genai/black-forest-labs/flux.1-schnell';
        return 'nvidia-' . (string)preg_replace('#^.*/#', '', rtrim($url, '/'));
    }

    /**
     * File circuit breaker: after one hard failure — or three consecutive
     * calls that never completed — the route is skipped for 30 minutes
     * (site-wide, not just this request) so disabled NIM image functions
     * never add latency to live traffic. A later success clears it.
     */
    private static function nvidiaCircuitState(): array
    {
        $file = ROOT_PATH . '/' . self::NVIDIA_BREAKER_FILE;
        if (!is_file($file)) {
            return ['open_until' => 0, 'misses' => 0];
        }
        $j = json_decode((string)file_get_contents($file), true);
        if (!is_array($j)) {
            return ['open_until' => 0, 'misses' => 0];
        }
        return [
            'open_until' => (int)($j['open_until'] ?? 0),
            'misses'     => (int)($j['misses'] ?? 0),
        ];
    }

    private static function nvidiaBreakerOpen(): bool
    {
        $state = self::nvidiaCircuitState();
        return $state['open_until'] > time();
    }

    private static function nvidiaWriteState(array $state): void
    {
        $dir = ROOT_PATH . '/cache';
        if (!is_dir($dir) && !@mkdir($dir, 0755, true) && !is_dir($dir)) {
            return;
        }
        @file_put_contents(
            ROOT_PATH . '/' . self::NVIDIA_BREAKER_FILE,
            json_encode($state)
        );
    }

    /** Hard failure (dead function, quota, network error) → open 30 minutes. */
    private static function nvidiaTripBreaker(): void
    {
        self::nvidiaWriteState(['open_until' => time() + 1800, 'misses' => 0]);
    }

    /** The route never finished (hung) → count a miss; 3 misses open it. */
    private static function nvidiaNoteMiss(): void
    {
        $state = self::nvidiaCircuitState();
        if ($state['open_until'] > time()) {
            return;
        }
        $misses = $state['misses'] + 1;
        self::nvidiaWriteState([
            'open_until' => $misses >= 3 ? time() + 1800 : 0,
            'misses'     => $misses,
        ]);
    }

    private static function nvidiaClearBreaker(): void
    {
        @unlink(ROOT_PATH . '/' . self::NVIDIA_BREAKER_FILE);
    }

    /**
     * Prepared cURL handle for one NVIDIA NIM image generation call.
     * Response contract: {"artifacts":[{"base64":"...","mimeType":"image/png"}]}
     */
    private static function nvidiaJob(string $prompt): array
    {
        $url     = defined('NVIDIA_IMAGE_URL') ? NVIDIA_IMAGE_URL : 'https://ai.api.nvidia.com/v1/genai/black-forest-labs/flux.1-schnell';
        $timeout = defined('NVIDIA_IMAGE_TIMEOUT') ? (int)NVIDIA_IMAGE_TIMEOUT : 75;

        $payload = json_encode([
            'prompt'    => $prompt,
            'cfg_scale' => 5.0,
            'mode'      => 'base',
            'steps'     => 4,
        ]);

        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_POST           => true,
            CURLOPT_POSTFIELDS     => $payload,
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT        => $timeout,
            CURLOPT_CONNECTTIMEOUT => 15,
            CURLOPT_SSL_VERIFYPEER => true,
            CURLOPT_SSL_VERIFYHOST => 2,
            CURLOPT_HTTPHEADER     => [
                'Authorization: Bearer ' . self::nvidiaApiKey(),
                'Accept: application/json',
                'Content-Type: application/json',
            ],
        ]);
        if (function_exists('ca_curl_setopt')) {
            ca_curl_setopt($ch);
        }
        return ['ch' => $ch, 'label' => 'NVIDIAImage[' . (string)preg_replace('#^.*/#', '', $url) . ']'];
    }

    /**
     * Extract the first artifact image from a NIM response.
     *
     * @return array{data:string,mime:string}|null
     */
    private static function parseNvidiaImageResponse(string $response): ?array
    {
        $json = json_decode($response, true);
        foreach ((array)($json['artifacts'] ?? []) as $artifact) {
            if (!empty($artifact['base64'])) {
                $data = base64_decode((string)$artifact['base64'], true);
                if ($data !== false && strlen($data) > 128) {
                    return [
                        'data' => $data,
                        'mime' => (string)($artifact['mimeType'] ?? 'image/png'),
                    ];
                }
            }
        }
        return null;
    }

    // ─── Pollinations (free, keyless) ────────────────────────────

    /**
     * Prepared cURL handle for one Pollinations image request.
     */
    private static function pollinationsJob(string $prompt, int $width, int $height): array
    {
        $width  = max(256, min(1536, $width));
        $height = max(256, min(1536, $height));

        $url = 'https://image.pollinations.ai/prompt/' . rawurlencode($prompt)
            . '?width=' . $width . '&height=' . $height . '&nologo=true&safe=true';

        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_FOLLOWLOCATION => true,
            CURLOPT_TIMEOUT        => 60,
            CURLOPT_CONNECTTIMEOUT => 15,
            CURLOPT_HTTPHEADER     => ['Accept: image/*'],
            CURLOPT_SSL_VERIFYPEER => true,
            CURLOPT_SSL_VERIFYHOST => 2,
        ]);
        if (function_exists('ca_curl_setopt')) {
            ca_curl_setopt($ch);
        }
        return ['ch' => $ch, 'label' => 'Pollinations'];
    }

    /**
     * Validate raw image bytes (Pollinations returns the image directly).
     *
     * @return array{data:string,mime:string}|null
     */
    private static function parseImageBytes(string $bytes): ?array
    {
        if (strlen($bytes) < 128 || !function_exists('getimagesizefromstring')) {
            return null;
        }
        $info = @getimagesizefromstring($bytes);
        if ($info === false || empty($info['mime']) || !str_starts_with((string)$info['mime'], 'image/')) {
            return null;
        }
        return ['data' => $bytes, 'mime' => (string)$info['mime']];
    }

    /**
     * Sequential Pollinations attempt with one rate-limit wait+retry.
     * Used as the post-race fallback when the pool produced nothing.
     */
    private static function pollinationsImage(string $prompt, int $width, int $height, ?string $saveAs): ?array
    {
        if (self::$pollinationsExhausted) {
            return null;
        }

        $resp = self::pollinationsFetch($prompt, $width, $height);

        // Anonymous free tier is rate-limited (~1 image / 45s per IP): wait
        // out an advertised short window and retry once before giving up.
        if ($resp['code'] === 402 || $resp['code'] === 429) {
            $wait = 0;
            if (preg_match('/Retry after (\d+)s/i', (string)$resp['body'], $m)) {
                $wait = (int)$m[1];
            }
            if ($wait > 0 && $wait <= 20) {
                sleep(min($wait, 20) + 1);
                $resp = self::pollinationsFetch($prompt, $width, $height);
            }
        }
        if ($resp['code'] === 402 || $resp['code'] === 429) {
            self::$pollinationsExhausted = true;
            error_log('Pollinations free-tier limit reached; skipping for the rest of this request.');
            return null;
        }
        if ($resp['code'] < 200 || $resp['code'] >= 300) {
            return null;
        }

        $bytes = self::parseImageBytes((string)$resp['body']);
        if ($bytes === null) {
            return null;
        }
        return self::persistImage($bytes, 'pollinations', $saveAs);
    }

    private static function pollinationsFetch(string $prompt, int $width, int $height): array
    {
        $job = self::pollinationsJob($prompt, $width, $height);
        $body = curl_exec($job['ch']);
        $code = (int)curl_getinfo($job['ch'], CURLINFO_HTTP_CODE);
        curl_close($job['ch']);
        return ['code' => $code, 'body' => (string)$body];
    }

    // ─── storage ─────────────────────────────────────────────────

    private static function storeImage(string $bytes, string $mime, ?string $saveAs): ?string
    {
        if ($bytes === '' || strlen($bytes) < 128) {
            return null;
        }

        $dirRel  = 'assets/uploads/ai/gemini';
        $dirAbs  = ROOT_PATH . '/' . $dirRel;
        if (!is_dir($dirAbs) && !@mkdir($dirAbs, 0755, true) && !is_dir($dirAbs)) {
            return null;
        }

        $ext = match (strtolower((string)preg_replace('#^.*/#', '', $mime))) {
            'image/jpeg', 'image/jpg' => 'jpg',
            'image/webp'              => 'webp',
            default                   => 'png',
        };

        $name = $saveAs !== null ? trim((string)$saveAs) : '';
        $name = preg_replace('/[^a-zA-Z0-9._-]/', '_', $name);
        $name = ltrim($name, '._');
        if ($name === '' || !str_ends_with(strtolower($name), '.' . $ext)) {
            $base   = $name !== '' ? preg_replace('/\.[a-z0-9]+$/i', '', $name) : '';
            $name   = ($base !== '' && $base !== null ? $base : 'gen_' . bin2hex(random_bytes(5))) . '.' . $ext;
        }

        $rel = $dirRel . '/' . $name;
        if (@file_put_contents(ROOT_PATH . '/' . $rel, $bytes) === false) {
            return null;
        }
        return $rel;
    }

    private static function aspectFor(int $w, int $h): string
    {
        if ($w <= 0 || $h <= 0) {
            return '1:1';
        }
        $ratio = $w / $h;
        $known = [
            '9:16' => 9 / 16, '16:9' => 16 / 9, '1:1' => 1.0,
            '4:3' => 4 / 3, '3:4' => 3 / 4, '4:5' => 4 / 5,
            '5:4' => 5 / 4, '3:2' => 3 / 2, '2:3' => 2 / 3,
            '21:9' => 21 / 9,
        ];
        $best = '1:1';
        $bestDiff = PHP_FLOAT_MAX;
        foreach ($known as $label => $r) {
            $diff = abs($ratio - $r);
            if ($diff < $bestDiff) {
                $bestDiff = $diff;
                $best = $label;
            }
        }
        return $best;
    }
}
